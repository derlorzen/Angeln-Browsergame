import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--enable-unsafe-swiftshader', '--use-angle=swiftshader'] });
const p = await b.newPage({ viewport: { width: 1366, height: 768 } });
const errs = [];
p.on('console', m => { if (m.type() === 'error' || m.type()==='warning') errs.push(m.text()); });
p.on('pageerror', e => errs.push('PAGEERROR ' + e.message));
await p.goto(process.env.BASE_URL ?? 'http://localhost:5173/');
await p.waitForTimeout(2500);
await p.screenshot({ path: '/tmp/claude-0/shots/menu-gl.png' });
await p.click('[data-a=sp]');
await p.click('[data-a=go]');
await p.waitForFunction(() => window.__game?.client?.units?.size > 0, null, {timeout: 20000});
await p.waitForTimeout(2000);
console.log('renderer', await p.evaluate(() => window.__game.renderer.kind));
await p.mouse.move(500, 250); await p.mouse.down(); await p.mouse.move(900, 550, {steps: 5}); await p.mouse.up();
await p.keyboard.press('e');
await p.mouse.move(760, 330);
await p.waitForTimeout(500);
await p.screenshot({ path: '/tmp/claude-0/shots/game-gl.png' });
console.log(errs.join('\n'));
await b.close();
